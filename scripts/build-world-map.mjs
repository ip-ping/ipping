// Turn Natural Earth's 110m land outline (public domain, https://www.naturalearthdata.com) into one
// compact SVG path in plain latitude/longitude ("equirectangular") coordinates:
//
//   node scripts/build-world-map.mjs
//
// x = longitude + 180 and y = 90 - latitude, so a point sits at (lon + 180, 90 - lat) in a
// 360 x 180 box. The result is committed (src/lib/geo/world-path.ts); nothing is fetched at runtime.
import { writeFile } from "node:fs/promises";

const SOURCE =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson";
const SOUTH_LIMIT = -58; // leave Antarctica out: no measurement node lives there

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE}: ${response.status}`);
const geo = await response.json();

const round = (n) => Math.round(n * 10) / 10;
const rings = [];
for (const feature of geo.features) {
  const { type, coordinates } = feature.geometry;
  const polygons = type === "Polygon" ? [coordinates] : coordinates;
  for (const polygon of polygons) {
    for (const ring of polygon) {
      if (Math.max(...ring.map(([, lat]) => lat)) < SOUTH_LIMIT) continue;
      rings.push(ring);
    }
  }
}

let path = "";
let points = 0;
for (const ring of rings) {
  let last = "";
  const segments = [];
  for (const [lon, lat] of ring) {
    const point = `${round(lon + 180)} ${round(90 - lat)}`;
    if (point === last) continue; // rounding makes neighbours collide
    segments.push(point);
    last = point;
  }
  if (segments.length < 3) continue;
  points += segments.length;
  path += `M${segments.join("L")}Z`;
}

const out = `// Generated by scripts/build-world-map.mjs from Natural Earth 110m land (public domain). Do not edit.
// Coordinates: x = longitude + 180, y = 90 - latitude.
export const WORLD_PATH =
  ${JSON.stringify(path)};
`;
await writeFile(new URL("../src/lib/geo/world-path.ts", import.meta.url), out);
console.log(`${rings.length} outlines, ${points} points, ${(out.length / 1024).toFixed(0)} KiB`);
